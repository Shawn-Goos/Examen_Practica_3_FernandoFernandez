    public void mostrarCocheActual() {
        System.out.println("FUNCINOA");
        if (listaCoches != null) {
            
            System.out.println("FUNCINOA");
            Coche c = listaCoches.obtenerCocheActual();
            if (c != null) {
                System.out.println("A");
                MatriculaCaja.setText(c.getMatricula());
                FechaMatCaja.setText(c.getFechaMatriculacion().toString());
                PrecioCaja.setText(String.valueOf(c.getPrecio()));
                
            } else {
                System.out.println("B");
                MatriculaCaja.setText("");
                FechaMatCaja.setText("");
                PrecioCaja.setText("");
                if (listaCoches.obtenerCocheActual() == null && !listaCoches.esVacia()) {
                    listaCoches.retroceder();
                    mostrarCocheActual();
                }
            }
        }
    }

